@dataclass
class ChatFilesDeps:
    store: ChatFileStore
    storage: ChatFilesStorage | None
    """``None`` without the bucket: nothing is uploaded nor downloaded (503)."""
    audit: AuditLog
    uploads: Limiter | None = None
    upload_bytes: Limiter | None = None
    checks: Limiter | None = None
    downloads: Limiter | None = None
    contents: Limiter | None = None
    clock: Callable[[], float] = field(default=time.time)


def _unavailable(exc: Exception) -> ApiError:
    logger.error("chat files unavailable: %s", type(exc).__name__)
    return ApiError(503, "files_unavailable", "please try again")


def _storage(deps: ChatFilesDeps) -> ChatFilesStorage:
    if deps.storage is None:
        raise ApiError(503, "files_unavailable", "please try again")
    return deps.storage


def _limit(limiter: Limiter | None, key: str, cost: int = 1) -> None:
    if limiter is None:
        return
    try:
        allowed = limiter.allow(key, cost)
    except RateLimitUnavailableError as exc:
        raise ApiError(503, "rate_limit_unavailable", "please try again") from exc
    if not allowed:
        raise rate_limited(limiter.retry_after(key, cost))


def _audit(deps: ChatFilesDeps, event: str, caller: Caller, **detail: Any) -> None:
    """Fail closed: what cannot be audited is not done (rule 4). Ids, kinds, sizes and hashes,
    never a name nor content (D116 (7), TM-CF8)."""
    try:
        deps.audit.emit(event, caller.user.user_id, detail, caller.user)
    except Exception as exc:
        raise ApiError(503, "audit_unavailable", "the action could not be audited; retry") from exc


def gone(f: ChatFile, now: float) -> bool:
    return f.deleted or now >= f.expires_at


def attachment_out(f: ChatFile, now: float) -> ChatAttachmentOut:
    status: ChatAttachmentStatus = (
        "scanning" if f.status is FileStatus.VERIFYING else f.status.value  # type: ignore[assignment]
    )
    return ChatAttachmentOut(
        file_id=f.file_id,
        name=f.name,
        kind=f.kind,
        size_bytes=f.size,
        status=status,
        origin="generated" if f.origin == "generated" else "upload",
        expires_at=datetime.fromtimestamp(f.expires_at, UTC),
        gone=gone(f, now),
    )


def request_uploads(
    deps: ChatFilesDeps, caller: Caller, conversation_id: str, body: ChatUploadsIn
) -> ChatUploadsOut:
    """Record and sign one POST per file of the closed list of up to 100 MB; the others are
    answered with their reason and never uploaded."""
    storage = _storage(deps)
    user_id = caller.user.user_id
    now = deps.clock()
    upload_id = knowledge.new_id(int(now * 1000))
    planned: list[tuple[str, str, int, str | None]] = []
    for f in body.files:
        name = display_name(f.name)
        if name is None:
            raise ApiError(422, "invalid_name", "a file has no visible name")
        kind = extension(name)
        status = (
            "unsupported_type"
            if kind is None
            else "too_large"
            if f.size > MAX_FILE_BYTES
            else "uploading"
        )
        planned.append((name, status, f.size, kind))
    accepted = [p for p in planned if p[1] == "uploading"]
    total = sum(p[2] for p in accepted)
    if accepted:
        # TM-CF6: files per hour and bytes per day, shared by every task (D70).
        _limit(deps.uploads, user_id, len(accepted))
        _limit(deps.upload_bytes, user_id, max(1, math.ceil(total / _MB)))
    _audit(
        deps,
        "chat.file_upload",
        caller,
        conversation_id=conversation_id,
        upload_id=upload_id,
        files=len(accepted),
        refused=len(planned) - len(accepted),
        bytes=total,
        outcome="requested",
    )
    at = int(now)
    out: list[ChatSignedUploadOut] = []
    records: list[ChatFile] = []
    try:
        for name, status, size, kind in planned:
            if status != "uploading" or kind is None:
                out.append(ChatSignedUploadOut(name=name, status=status))  # type: ignore[arg-type]
                continue
            file_id = knowledge.new_id(int(now * 1000))
            fields = storage.sign_upload(
                upload_key(user_id, upload_id, file_id),
                size,
                TYPES[kind].content_type,
                user_id=user_id,
            )
            records.append(
                ChatFile(
                    file_id=file_id,
                    conversation_id=conversation_id,
                    owner=user_id,
                    origin="upload",
                    name=name,
                    kind=kind,
                    size=size,
                    status=FileStatus.UPLOADING,
                    status_at=at,
                    created_at=at,
                    expires_at=at + RETENTION_SECONDS,
                    upload_id=upload_id,
                )
            )
            out.append(
                ChatSignedUploadOut(
                    name=name, status="uploading", file_id=file_id, url=storage.url, fields=fields
                )
            )
        deps.store.put_new(user_id, records)
    except (ChatFilesStorageUnavailableError, ChatFileStoreUnavailableError) as exc:
        raise _unavailable(exc) from exc
    return ChatUploadsOut(
        upload_id=upload_id,
        expires_at=datetime.fromtimestamp(now + UPLOAD_SECONDS, UTC),
        files=out,
    )


def _timed_out(f: ChatFile, now: int) -> bool:
    return now - f.status_at > SCAN_TIMEOUT_SECONDS


def advance(deps: ChatFilesDeps, caller: Caller | None, f: ChatFile) -> ChatFile:
    """Move a file as far as its scans allow (steps 3 and 4 of the module). Idempotent: two
    requests at once move it once (conditional writes); the loser reads it again."""
    storage = _storage(deps)
    for _ in range(3):
        now = int(deps.clock())
        if f.status in ENDED or f.status is FileStatus.UPLOADING or gone(f, now):
            return f
        moved = (
            _scanning(deps, storage, caller, f, now)
            if f.status is FileStatus.SCANNING
            else _verifying(deps, caller, f, now)
        )
        if moved is None:
            # Another request moved it first.
            again = deps.store.file(f.owner, f.conversation_id, f.file_id)
            if again is None:
                return f
            f = again
            continue
        if moved.status == f.status:
            return moved
        f = moved
    return f


def _scanning(  # noqa: PLR0911 - one return per step of the check
    deps: ChatFilesDeps, storage: ChatFilesStorage, caller: Caller | None, f: ChatFile, now: int
) -> ChatFile | None:
    source = upload_key(f.owner, f.upload_id, f.file_id)
    scan = deps.store.scan(f.owner, source)
    if scan is None:
        return deps.store.move(f, FileStatus.FAILED, now=now) if _timed_out(f, now) else f
    if scan_outcome(scan.result) is ScanOutcome.BLOCKED:
        return _end(deps, caller, f, FileStatus.BLOCKED, now)
    inspected = storage.inspect(source, f.kind, f'"{scan.etag}"')
    if inspected is None:
        # Replaced since the scan (the POST lasts 15 minutes): its own scan will say.
        return deps.store.move(f, FileStatus.FAILED, now=now) if _timed_out(f, now) else f
    if inspected.size != f.size:
        status = FileStatus.TOO_LARGE if inspected.size > MAX_FILE_BYTES else FileStatus.FAILED
        return _end(deps, caller, f, status, now)
    if not inspected.matches:
        return _end(deps, caller, f, FileStatus.TYPE_MISMATCH, now)
    # Taken before the copy: of two requests at once only one copies.
    taken = deps.store.move(f, FileStatus.VERIFYING, now=now)
    if taken is None:
        return None
    destination = owner_key(f.owner, f.conversation_id, f.file_id)
    try:
        sha256 = storage.copy(source, f'"{scan.etag}"', destination, TYPES[f.kind].content_type)
    except ChatFilesStorageUnavailableError:
        # Back to its scan: the next confirmation copies it again.
        deps.store.move(taken, FileStatus.SCANNING, now=now)
        raise
    if sha256 is None:
        return deps.store.move(taken, FileStatus.FAILED, now=now)
    return deps.store.move(taken, FileStatus.VERIFYING, now=now, sha256=sha256) or taken


def _verifying(
    deps: ChatFilesDeps, caller: Caller | None, f: ChatFile, now: int
) -> ChatFile | None:
    scan = deps.store.scan(f.owner, owner_key(f.owner, f.conversation_id, f.file_id))
    if scan is None:
        return deps.store.move(f, FileStatus.FAILED, now=now) if _timed_out(f, now) else f
    if scan_outcome(scan.result) is ScanOutcome.BLOCKED:
        return _end(deps, caller, f, FileStatus.BLOCKED, now)
    return _end(deps, caller, f, FileStatus.READY, now)


def _end(
    deps: ChatFilesDeps, caller: Caller | None, f: ChatFile, status: FileStatus, now: int
) -> ChatFile | None:
    moved = deps.store.move(f, status, now=now)
    if moved is not None and caller is not None:
        # The end of each file, with what it is; never its name (D116 (7)).
        try:
            deps.audit.emit(
                "chat.file_upload",
                caller.user.user_id,
                {
                    "conversation_id": f.conversation_id,
                    "upload_id": f.upload_id,
                    "file_id": f.file_id,
                    "kind": f.kind,
                    "size": f.size,
                    "sha256": moved.sha256,
                    "outcome": "applied" if status is FileStatus.READY else "rejected",
                    "reason": None if status is FileStatus.READY else status.value,
                },
                caller.user,
            )
        except Exception:
            # The file is recorded already; its end is in the record and the scan metric.
            logger.exception("the end of a chat upload could not be audited")
    return moved


def confirm_uploads(
    deps: ChatFilesDeps, caller: Caller, conversation_id: str, upload_id: str, body: ChatConfirmIn
) -> ChatAttachmentsOut:
    """The browser posted these files (or asks again how they are): each moves as far as its
    scans allow. Only files of this upload, conversation and person, while it lasts."""
    user_id = caller.user.user_id
    out: list[ChatAttachmentOut] = []
    try:
        for file_id in dict.fromkeys(body.file_ids):
            f = deps.store.file(user_id, conversation_id, file_id)
            if f is None or f.upload_id != upload_id or f.origin != "upload":
                raise ApiError(404, "unknown_file", "a file is not of this upload")
            now = int(deps.clock())
            if f.status is FileStatus.UPLOADING:
                if now - f.created_at > CONFIRM_SECONDS:
                    f = deps.store.move(f, FileStatus.FAILED, now=now) or f
                else:
                    f = deps.store.move(f, FileStatus.SCANNING, now=now) or (
                        deps.store.file(user_id, conversation_id, file_id) or f
                    )
            out.append(attachment_out(advance(deps, caller, f), deps.clock()))
    except (ChatFilesStorageUnavailableError, ChatFileStoreUnavailableError) as exc:
        raise _unavailable(exc) from exc
    return ChatAttachmentsOut(files=out)


@dataclass
class StoreAttachments:
    """Attachments of a turn, from the records (``Attachments``)."""

    deps: ChatFilesDeps

    def ready(self, user_id: str, conversation_id: str, file_ids: Sequence[str]) -> list[ChatFile]:
        """The files of a message (TM-CF9): each one an upload of this conversation and person,
        ``ready`` and not gone; otherwise 422 ``attachment_not_ready``, or 404 when it is not
        of this conversation. In the order given, once each."""
        found: list[ChatFile] = []
        try:
            for file_id in dict.fromkeys(file_ids):
                f = self.deps.store.file(user_id, conversation_id, file_id)
                if f is None or f.origin != "upload":
                    raise ApiError(
                        404, "unknown_attachment", "an attachment is not of this conversation"
                    )
                if f.status is not FileStatus.READY and self.deps.storage is not None:
                    f = advance(self.deps, None, f)
                if f.status is not FileStatus.READY or gone(f, self.deps.clock()):
                    raise ApiError(422, "attachment_not_ready", "an attachment is not ready")
                found.append(f)
        except (ChatFilesStorageUnavailableError, ChatFileStoreUnavailableError) as exc:
            raise _unavailable(exc) from exc
        return found


def turn_attachments(
    deps: "ChatFilesDeps | None", user_id: str, conversation_id: str, file_ids: Sequence[str]
) -> list[ChatFile]:
    """The files of a question, checked (``StoreAttachments.ready``); none without ids."""
    if not file_ids:
        return []
    if deps is None:
        raise ApiError(503, "files_unavailable", "please try again")
    return StoreAttachments(deps).ready(user_id, conversation_id, file_ids)


def present(deps: "ChatFilesDeps | None", user_id: str, conversation_id: str) -> frozenset[str]:
    """Ids of the files of a conversation that are still there, for the history; none when
    they cannot be read (the history shows them as gone rather than failing)."""
    if deps is None:
        return frozenset()
    now = deps.clock()
    try:
        files = deps.store.files(user_id, conversation_id)
    except ChatFileStoreUnavailableError:
        logger.exception("the files of a conversation could not be read")
        return frozenset()
    return frozenset(f.file_id for f in files if not gone(f, now))


def snapshot(files: Sequence[ChatFile]) -> list[dict[str, Any]]:
    """What a message keeps of its attachments: enough for the history, never a key."""
    return [{"file_id": f.file_id, "name": f.name, "kind": f.kind, "size": f.size} for f in files]


def _deliverable(deps: ChatFilesDeps, f: ChatFile | None) -> ChatFile:
    if f is None:
        raise HTTPException(status_code=404, detail="not found")
    now = deps.clock()
    if gone(f, now):
        raise ApiError(410, "file_gone", "the file is no longer available")
    if f.status is FileStatus.BLOCKED:
        raise ApiError(409, "file_blocked", "the malware scan blocked this file")
    if f.status is not FileStatus.READY:
        raise ApiError(409, "file_not_ready", "the file is not ready yet")
    return f


def download_link(deps: ChatFilesDeps, caller: Caller, f: ChatFile) -> ChatFileLinkOut:
    """A new link of 5 minutes to a file of the caller's conversation, audited first."""
    storage = _storage(deps)
    _limit(deps.downloads, caller.user.user_id)
    _audit(
        deps,
        "chat.file_download",
        caller,
        conversation_id=f.conversation_id,
        file_id=f.file_id,
        kind=f.kind,
        size=f.size,
        sha256=f.sha256,
        origin=f.origin,
        outcome="applied",
    )
    try:
        url = storage.link(
            owner_key(f.owner, f.conversation_id, f.file_id),
            f.name,
            TYPES[f.kind].content_type,
            user_id=f.owner,
        )
    except ChatFilesStorageUnavailableError as exc:
        raise _unavailable(exc) from exc
    return ChatFileLinkOut(url=url, file=f.name)


_CONTENT_HEADERS = {
    "X-Content-Type-Options": "nosniff",
    "Cache-Control": "private, no-store",
    # Opened on its own it runs nothing (TM-CF4); the SPA reads it with fetch as a blob.
    "Content-Security-Policy": "default-src 'none'; sandbox",
    "Cross-Origin-Resource-Policy": "same-origin",
}


def content(deps: ChatFilesDeps, caller: Caller, f: ChatFile) -> StreamingResponse:
    """The bytes of an image of the conversation, for a ``blob:`` of the SPA (D116 (5)): only
    PNG and JPEG whose first bytes are still of that kind, with the type of the server."""
    kind = TYPES.get(f.kind)
    if kind is None or not kind.image:
        raise ApiError(415, "not_an_image", "only images are shown in the chat")
    storage = _storage(deps)
    _limit(deps.contents, caller.user.user_id)
    _audit(
        deps,
        "chat.file_download",
        caller,
        conversation_id=f.conversation_id,
        file_id=f.file_id,
        kind=f.kind,
        size=f.size,
        sha256=f.sha256,
        origin=f.origin,
        inline=True,
        outcome="applied",
    )
    try:
        chunks = storage.open(owner_key(f.owner, f.conversation_id, f.file_id))
        first = next(chunks, b"") if chunks is not None else b""
    except ChatFilesStorageUnavailableError as exc:
        raise _unavailable(exc) from exc
    if chunks is None or not content_matches(f.kind, first, b"", f.size):
        raise ApiError(409, "file_not_ready", "the file is not ready yet")

    def body() -> Iterator[bytes]:
        yield first
        yield from chunks

    return StreamingResponse(
        body(),
        media_type=kind.content_type,
        headers={**_CONTENT_HEADERS, "Content-Disposition": content_disposition(f.name)},
    )


def delete_conversation_files(deps: ChatFilesDeps, caller: Caller, conversation_id: str) -> int:
    """D116 (9), TM-CF7: deleting a conversation (or its person) deletes its files, uploaded
    and generated, and marks their records gone; audited with counts. The number deleted.
    Called by the deletion of a conversation, which has no route yet."""
    storage = _storage(deps)
    user_id = caller.user.user_id
    try:
        files = [f for f in deps.store.files(user_id, conversation_id) if not f.deleted]
        keys = [owner_key(user_id, conversation_id, f.file_id) for f in files]
        keys += [upload_key(user_id, f.upload_id, f.file_id) for f in files if f.upload_id]
        _audit(
            deps,
            "chat.file_delete",
            caller,
            conversation_id=conversation_id,
            files=len(files),
            outcome="requested",
        )
        storage.delete(keys)
        now = int(deps.clock())
        for f in files:
            deps.store.mark_deleted(f, now=now)
    except (ChatFilesStorageUnavailableError, ChatFileStoreUnavailableError) as exc:
        raise _unavailable(exc) from exc
    return len(files)


# --- Router -----------------------------------------------------------------------------

OwnConversation = Callable[[Caller, str, str, bool], Awaitable[None]]
"""``(caller, conversation_id, owner, read_only)``: L1 ``OwnConversation``, audited, 404 when
denied (``app.own_conversation``)."""
ConversationOwner = Callable[[str, str], str | None]
"""``(user_id, conversation_id)``: the owner of a stored conversation of the caller's partition,
or ``None`` when it is not stored yet."""


def chat_files_router(
    deps: ChatFilesDeps,
    current_user: Callable[..., Awaitable[Caller]],
    own: OwnConversation,
    owner_of: ConversationOwner,
) -> APIRouter:
    router = APIRouter(prefix="/api/conversations")
    ConversationId = Annotated[str, Path(pattern=r"^[0-9a-f]{32}$")]  # noqa: N806
    UploadId = Annotated[str, Path(pattern=knowledge.ID_PATTERN)]  # noqa: N806
    FilePath = Annotated[str, Path(pattern=knowledge.ID_PATTERN)]  # noqa: N806
    SignedIn = Annotated[Caller, Depends(current_user)]  # noqa: N806

    async def run[T](fn: Callable[..., T], *args: Any, **kwargs: Any) -> T:
        return await asyncio.to_thread(fn, *args, **kwargs)

    async def writable(caller: Caller, conversation_id: str) -> None:
        """A conversation of the caller: stored (its owner, by Cedar) or about to be (a new
        chat whose first message carries the files, in the caller's own partition)."""
        owner = await run(owner_of, caller.user.user_id, conversation_id)
        await own(caller, conversation_id, owner or caller.user.user_id, False)

    async def file_of(caller: Caller, conversation_id: str, file_id: str) -> ChatFile:
        """A file of the caller's partition, then ``OwnConversation`` with its record's owner:
        someone else's and one that does not exist answer the same 404 (TM-CF1)."""
        try:
            f = await run(deps.store.file, caller.user.user_id, conversation_id, file_id)
        except ChatFileStoreUnavailableError as exc:
            raise _unavailable(exc) from exc
        if f is None:
            raise HTTPException(status_code=404, detail="not found")
        await own(caller, conversation_id, f.owner, True)
        return f

    @router.post("/{conversation_id}/uploads", response_model=ChatUploadsOut, status_code=201)
    async def request_chat_uploads(
        conversation_id: ConversationId, body: ChatUploadsIn, caller: SignedIn
    ) -> ChatUploadsOut:
        await writable(caller, conversation_id)
        return await run(request_uploads, deps, caller, conversation_id, body)

    @router.post(
        "/{conversation_id}/uploads/{upload_id}/confirm", response_model=ChatAttachmentsOut
    )
    async def confirm_chat_uploads(
        conversation_id: ConversationId, upload_id: UploadId, body: ChatConfirmIn, caller: SignedIn
    ) -> ChatAttachmentsOut:
        """Idempotent: the composer calls it once the POSTs end and again to follow the
        scans («Revisando el archivo…»)."""
        await writable(caller, conversation_id)
        _limit(deps.checks, caller.user.user_id)
        return await run(confirm_uploads, deps, caller, conversation_id, upload_id, body)

    @router.post("/{conversation_id}/files/{file_id}/download", response_model=ChatFileLinkOut)
    async def download_chat_file(
        conversation_id: ConversationId, file_id: FilePath, _body: ChatEmptyIn, caller: SignedIn
    ) -> ChatFileLinkOut:
        f = _deliverable(deps, await file_of(caller, conversation_id, file_id))
        return await run(download_link, deps, caller, f)

    @router.get(
        "/{conversation_id}/files/{file_id}/content",
        responses={200: {"content": {"image/png": {}, "image/jpeg": {}}}},
    )
    async def chat_file_content(
        conversation_id: ConversationId, file_id: FilePath, caller: SignedIn
    ) -> StreamingResponse:
        f = _deliverable(deps, await file_of(caller, conversation_id, file_id))
        return await run(content, deps, caller, f)

    return router
