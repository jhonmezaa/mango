class ChatFilesStorageUnavailableError(Exception):
    """S3 or the signer could not answer; callers fail closed."""


@dataclass(frozen=True)
class Inspected:
    size: int
    matches: bool


def _code(exc: ClientError) -> str:
    return str(exc.response.get("Error", {}).get("Code", ""))


_NOT_READABLE = {"403", "AccessDenied", "404", "NoSuchKey", "NotFound", "412", "PreconditionFailed"}
"""An object that is not there, that the bucket does not let anybody read yet (no clean tag),
or that is no longer the version the scan cleared."""


def content_disposition(name: str) -> str:
    """``attachment`` with the name in RFC 6266/5987: an ASCII fallback and the UTF-8 name, so
    quotes, accents and line breaks never break the header."""
    fallback = "".join(
        c if c.isascii() and c.isprintable() and c not in '"\\;' else "_" for c in name
    )
    return f"attachment; filename=\"{fallback}\"; filename*=UTF-8''{quote(name, safe='')}"


class ChatFilesStorage:
    """The bucket ``Mango-<ns>-chat-files``. ``s3`` checks, copies, reads images and deletes with
    mango-api's own credentials; ``signer`` signs every URL a browser uses, never those."""

    def __init__(
        self, s3: "S3Client", bucket: str, region: str, signer: PresignSessions | None
    ) -> None:
        self._s3 = s3
        self._bucket = bucket
        self._signer = signer
        # The signature of a POST covers its policy, not the host: the regional host is the
        # only one the CSP of the SPA allows.
        self.url = f"https://{bucket}.s3.{region}.amazonaws.com/"

    def _signing(self, user_id: str) -> "S3Client":
        if self._signer is None:
            raise ChatFilesStorageUnavailableError("no signing role")
        try:
            return self._signer.s3_for(user_id)
        except SigningUnavailableError as exc:
            raise ChatFilesStorageUnavailableError("signing unavailable") from exc

    def sign_upload(
        self, key: str, size: int, content_type: str, *, user_id: str
    ) -> dict[str, str]:
        """The fields of a POST that only uploads ``key``, of exactly ``size`` bytes and
        ``content_type``, signed by the presign role for ``user_id``."""
        try:
            signed = self._signing(user_id).generate_presigned_post(
                Bucket=self._bucket,
                Key=key,
                Fields={"Content-Type": content_type},
                Conditions=[
                    {"bucket": self._bucket},
                    ["eq", "$key", key],
                    {"Content-Type": content_type},
                    ["content-length-range", size, size],
                ],
                ExpiresIn=UPLOAD_SECONDS,
            )
        except (BotoCoreError, ClientError) as exc:
            raise ChatFilesStorageUnavailableError(type(exc).__name__) from exc
        return dict(signed["fields"])

    def inspect(self, key: str, kind: str, etag: str) -> Inspected | None:
        """Size and bytes of the object the scan cleared (``etag``); ``None`` while it cannot
        be read (not clean yet, or replaced since)."""
        try:
            head = self._s3.head_object(Bucket=self._bucket, Key=key, IfMatch=etag)
            size = int(head["ContentLength"])
            if size == 0 or size > MAX_FILE_BYTES:
                return Inspected(size, matches=False)
            first = self._range(key, f"bytes=0-{HEAD_BYTES - 1}", etag)
            last = self._range(key, f"bytes=-{TAIL_BYTES}", etag) if needs_tail(kind) else b""
        except ClientError as exc:
            if _code(exc) in _NOT_READABLE:
                return None
            raise ChatFilesStorageUnavailableError(_code(exc)) from exc
        except BotoCoreError as exc:
            raise ChatFilesStorageUnavailableError(type(exc).__name__) from exc
        return Inspected(size, matches=content_matches(kind, first, last, size))

    def _range(self, key: str, byte_range: str, etag: str) -> bytes:
        response = self._s3.get_object(Bucket=self._bucket, Key=key, Range=byte_range, IfMatch=etag)
        return response["Body"].read()

    def copy(self, source: str, etag: str, destination: str, content_type: str) -> str | None:
        """Copy the object the scan cleared, and only that one, without its tags: the copy is
        scanned on its own. The SHA-256 S3 computes, in hex; ``None`` when the source cannot be
        read any more."""
        try:
            response = self._s3.copy_object(
                Bucket=self._bucket,
                Key=destination,
                CopySource={"Bucket": self._bucket, "Key": source},
                CopySourceIfMatch=etag,
                MetadataDirective="REPLACE",
                TaggingDirective="REPLACE",
                ContentType=content_type,
                ChecksumAlgorithm="SHA256",
            )
        except ClientError as exc:
            if _code(exc) in _NOT_READABLE:
                return None
            raise ChatFilesStorageUnavailableError(_code(exc)) from exc
        except BotoCoreError as exc:
            raise ChatFilesStorageUnavailableError(type(exc).__name__) from exc
        checksum: Any = response.get("CopyObjectResult", {}).get("ChecksumSHA256", "")
        return base64.b64decode(checksum).hex() if checksum else ""

    def link(self, key: str, name: str, content_type: str, *, user_id: str) -> str:
        """A link to ``key`` for its owner (the session of the signature is theirs, rule 5)."""
        try:
            return self._signing(user_id).generate_presigned_url(
                "get_object",
                Params={
                    "Bucket": self._bucket,
                    "Key": key,
                    "ResponseContentType": content_type,
                    "ResponseContentDisposition": content_disposition(name),
                },
                ExpiresIn=LINK_SECONDS,
            )
        except (BotoCoreError, ClientError) as exc:
            raise ChatFilesStorageUnavailableError(type(exc).__name__) from exc

    def open(self, key: str) -> Iterator[bytes] | None:
        """The bytes of ``key`` in chunks; ``None`` when it cannot be read."""
        try:
            body = self._s3.get_object(Bucket=self._bucket, Key=key)["Body"]
        except ClientError as exc:
            if _code(exc) in _NOT_READABLE:
                return None
            raise ChatFilesStorageUnavailableError(_code(exc)) from exc
        except BotoCoreError as exc:
            raise ChatFilesStorageUnavailableError(type(exc).__name__) from exc
        return iter(lambda: body.read(CONTENT_CHUNK), b"")

    def delete(self, keys: Sequence[str]) -> None:
        """Delete the current version of each key; older ones go the next day (lifecycle)."""
        try:
            for key in keys:
                self._s3.delete_object(Bucket=self._bucket, Key=key)
        except (BotoCoreError, ClientError) as exc:
            raise ChatFilesStorageUnavailableError(type(exc).__name__) from exc


