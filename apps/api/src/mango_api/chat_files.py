"""Files of the chat (D116): what a person attaches to a message, and the download of the files of
a conversation (uploaded or generated by the code sandbox). Threat model
``chat-files-threat-model.md``.

The life of an attachment (``chat_files_store.FileStatus``):

1. ``POST /api/conversations/{id}/uploads`` announces up to 20 files of up to 100 MB. Each one
   that is of a kind of the closed list gets a POST signed by ``Mango-<ns>-Presign`` for one key
   made of ids (``uploads/<sub>/<upload>/<file>``), its exact size and the type of its
   extension, for 15 minutes (D88 (9), (33)): ``uploading``.
2. The browser posts it straight to S3 and says so (``…/uploads/{upload}/confirm``):
   ``scanning``. GuardDuty scans the object; the function ``Mango-<ns>-ChatFilesScan`` records
   what it said. Until it says ``NO_THREATS_FOUND`` the bucket lets nobody read it (TBAC,
   D116 (10)), so nothing is checked before.
3. Clean: mango-api checks its size and bytes against what was announced and copies it, only
   the object the scan cleared (its ETag), to ``owner/<sub>/conv/<conversation>/<file>``,
   without tags: ``verifying``. The copy is a new object and is scanned again.
4. The copy is clean: ``ready``. Any other result of either scan: ``blocked``; bytes of another
   kind: ``type_mismatch``; another size: ``too_large`` or ``failed``.

``confirm`` is idempotent and is what the browser calls again to follow its files: each call
moves them as far as the scans allow. A turn only takes files that are ``ready``, of its
conversation and of its person (``ChatRequest.attachments``, TM-CF9).

Downloads (D116 (5), TM-CF1, TM-CF4, TM-CF5): a link presigned by ``Mango-<ns>-Presign`` for the
owner, 5 minutes, always ``attachment``, with the type of the file's kind, audited before it is
issued, 60 per person and hour. Images are also served by mango-api itself (``…/content``) for
the SPA to show them as ``blob:``, with a fixed type, ``nosniff`` and a CSP that runs nothing.
After 90 days, or once deleted with its conversation, a file is ``gone``.

Security notes (security-best-practices, FastAPI):
* Every file is looked up in the caller's partition (row-level security) and Cedar decides
  ``OwnConversation`` with the owner of its record; someone else's file and one that does not
  exist answer the same 404.
* Keys come from the record, made of ids; the name a person gave never reaches S3 nor a log.
* Nothing is signed with the task's credentials; no URL is logged or stored.
* Every check fails closed: a store, S3, the signer or the audit that cannot answer is a 503.
"""

